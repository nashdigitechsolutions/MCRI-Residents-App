// Generates every icon variant from lib/assets/logo.png + LogoGeometry.
//
//   dart run tool/generate_brand_assets.dart
//   dart run flutter_launcher_icons
//   dart run flutter_native_splash:create
//
// Outputs:
//   assets/branding/app_icon.png          iOS + legacy Android (full logo)
//   assets/branding/adaptive_fg.png       Android adaptive foreground (badge, safe zone)
//   assets/branding/adaptive_bg.png       Android adaptive background (logo's two-tone)
//   (monochrome.png: flutter test tool/render_monochrome_test.dart)
//   assets/branding/splash_badge.png      badge on transparent, for splash
//   android/.../drawable/ic_notification.xml  notification icon (vector, white)
import 'dart:io';
import 'dart:math' as math;

import 'package:image/image.dart' as img;
import 'package:mcri_residents_app/theme/logo_geometry.dart';

const _out = 'assets/branding';

// The circular badge in the 1024 logo.
const _cx = 512.0, _cy = 512.0, _badgeR = 392.0;

void main() {
  Directory(_out).createSync(recursive: true);
  final logo = img.decodePng(File('lib/assets/logo.png').readAsBytesSync())!;

  // 1. Full logo for iOS (no alpha allowed) and legacy Android.
  File('$_out/app_icon.png').writeAsBytesSync(img.encodePng(logo));

  // 2. Badge cut out as an anti-aliased circle.
  final badge = _circleCrop(logo);
  File('$_out/splash_badge.png').writeAsBytesSync(img.encodePng(badge));

  // 3. Adaptive foreground: badge inside the 66/108 safe zone so no launcher
  //    mask (circle, squircle, teardrop) ever clips it.
  final fg = img.Image(width: 1024, height: 1024, numChannels: 4);
  const safe = 1024 * 66 / 108; // ~626px
  final scaled = img.copyResize(
    badge,
    width: safe.round(),
    height: safe.round(),
    interpolation: img.Interpolation.cubic,
  );
  img.compositeImage(
    fg,
    scaled,
    dstX: ((1024 - safe) / 2).round(),
    dstY: ((1024 - safe) / 2).round(),
  );
  File('$_out/adaptive_fg.png').writeAsBytesSync(img.encodePng(fg));

  // 4. Adaptive background: the logo's own split backdrop.
  final left = logo.getPixel(40, 40), right = logo.getPixel(984, 40);
  final bg = img.Image(width: 1024, height: 1024);
  for (var y = 0; y < 1024; y++) {
    for (var x = 0; x < 1024; x++) {
      bg.setPixel(x, y, x < 512 ? left : right);
    }
  }
  File('$_out/adaptive_bg.png').writeAsBytesSync(img.encodePng(bg));

  // 5. Monochrome themed icon is rendered with Flutter's canvas (cleaner
  //    diagonal strokes): flutter test tool/render_monochrome_test.dart

  // 6. Notification icon as a vector drawable (crisp at every density).
  File('android/app/src/main/res/drawable/ic_notification.xml')
      .writeAsStringSync(_notificationVector());

  stdout.writeln('Brand assets generated.');
}

img.Image _circleCrop(img.Image src) {
  final size = (_badgeR * 2).ceil();
  final out = img.Image(width: size, height: size, numChannels: 4);
  final x0 = (_cx - _badgeR).round(), y0 = (_cy - _badgeR).round();
  for (var y = 0; y < size; y++) {
    for (var x = 0; x < size; x++) {
      final dx = x + 0.5 - _badgeR, dy = y + 0.5 - _badgeR;
      final d = math.sqrt(dx * dx + dy * dy);
      final a = (_badgeR - d + 0.5).clamp(0.0, 1.0); // 1px soft edge
      if (a <= 0) continue;
      final p = src.getPixel(x0 + x, y0 + y);
      out.setPixelRgba(x, y, p.r, p.g, p.b, (255 * a).round());
    }
  }
  return out;
}

String _notificationVector() {
  String d(List<(double, double)> pts) =>
      'M${pts.map((p) => '${p.$1.toStringAsFixed(0)},${p.$2.toStringAsFixed(0)}').join(' L')}';
  // Content spans ~212..812 x 214..720; crop the viewport to it (+padding)
  // so the mark fills the 24dp status-bar slot.
  const vx = 150.0, vy = 150.0, vs = 724.0;
  final house = LogoGeometry.house.map(d).join(' ');
  final m = LogoGeometry.m.map(d).join(' ');
  return '''
<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/generate_brand_assets.dart from LogoGeometry. Do not edit. -->
<!-- Status-bar icon: white mark on transparent (Android tints it). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="$vs"
    android:viewportHeight="$vs">
    <group android:translateX="-$vx" android:translateY="-$vy">
        <path
            android:pathData="$house"
            android:strokeColor="#FFFFFFFF"
            android:strokeWidth="44"
            android:strokeLineJoin="miter"
            android:strokeLineCap="square" />
        <path
            android:pathData="$m"
            android:strokeColor="#FFFFFFFF"
            android:strokeWidth="70"
            android:strokeLineJoin="miter"
            android:strokeLineCap="butt" />
    </group>
</vector>
''';
}
